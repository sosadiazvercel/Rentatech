import 'dotenv/config';
import EmbeddedPostgres from 'embedded-postgres';
import { existsSync } from 'node:fs';
import { migrate } from './migrate';
import { seed } from './seed';
const url = new URL(process.env.DATABASE_URL || '');
if(process.env.APP_ENV !== 'development' || url.hostname !== '127.0.0.1' || !url.pathname.endsWith('_dev')) throw new Error('Only local _dev database allowed');
const db = new EmbeddedPostgres({ databaseDir: '.local/postgres', user: url.username, password: url.password, port: Number(url.port), persistent: true, postgresFlags: ['-h','127.0.0.1'], onLog: ()=>{}, onError: (e)=>console.error(String(e)) });
if(!existsSync('.local/postgres/PG_VERSION')) await db.initialise();
await db.start();
const client=db.getPgClient();await client.connect();
const name=url.pathname.slice(1);
if(!(await client.query('SELECT 1 FROM pg_database WHERE datname=$1',[name])).rowCount) await db.createDatabase(name);
await client.end();
await migrate(url.toString(),true);await seed(url.toString());
console.log('PostgreSQL local ready on 127.0.0.1:'+url.port+'. Ctrl+C to stop.');
let stopping=false;
for(const signal of ['SIGINT','SIGTERM'] as const) process.on(signal, async()=>{ if(stopping)return;stopping=true;await db.stop();process.exit(0); });
setInterval(()=>{},60000);
